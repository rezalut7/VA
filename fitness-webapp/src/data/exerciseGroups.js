// Exercise library, source: trainer-provided spreadsheet.
// Each exercise can define up to 4 independent selection dimensions:
//   equipment — снаряд/тренажёр/угол
//   side      — рабочая сторона (одна рука / две руки)
//   width     — ширина хвата (узкий/средний/широкий)
//   grip      — тип хвата (прямой/нейтральный/обратный)
// Any dimension left as [] is simply not shown in the picker.
// The old "variant" field still exists for a few miscellaneous exercises
// that need a single extra dimension not covered by the four above
// (e.g. "Скручивания" — прямые/боковые — not a grip concept at all).
// Cardio exercises measure by time/distance/reps instead of sets.

function ex(name, opts = {}) {
  return {
    name,
    equipment: opts.equipment || [],
    side: opts.side || [],
    width: opts.width || [],
    grip: opts.grip || [],
    variant: opts.variant || [],
  };
}

