// Снаряды, которые превращают упражнение в "ассистируемое" (гравитрон,
// резина — чем больше цифра/сопротивление, тем легче).
const ASSISTED_EQUIPMENT = ["Гравитрон", "Резинка"];

// Значения "рабочей стороны", при выборе которых обычное (двустороннее)
// упражнение фактически выполняется в одностороннем варианте — тогда его
// стоит считать унилатеральным, даже если базовая классификация — "base".
const UNILATERAL_SIDE_VALUES = ["Одна рука", "Одна нога"];

// Определяет фактический тип упражнения с учётом снаряда и стороны
// конкретной вариации (например "Подтягивания" обычно base, но на
// гравитроне — assisted; "Тяга верхнего блока" обычно base, но одной
// рукой — unilateral).
export function resolveExerciseType(baseName, equipment, side) {
  if (equipment && ASSISTED_EQUIPMENT.includes(equipment)) return "assisted";
  const base = EXERCISE_TYPES[baseName] || null;
  if (base === "base" && side && UNILATERAL_SIDE_VALUES.includes(side)) return "unilateral";
  return base;
}
