// Снаряды, которые превращают базовое/любое упражнение в "ассистируемое"
// (гравитрон, резина — чем больше цифра/сопротивление, тем легче).
const ASSISTED_EQUIPMENT = ["Гравитрон", "Резинка"];

// Определяет фактический тип упражнения с учётом снаряда конкретной вариации
// (например "Подтягивания" обычно base, но на гравитроне — assisted).
export function resolveExerciseType(baseName, equipment) {
  if (equipment && ASSISTED_EQUIPMENT.includes(equipment)) return "assisted";
  return EXERCISE_TYPES[baseName] || null;
}
